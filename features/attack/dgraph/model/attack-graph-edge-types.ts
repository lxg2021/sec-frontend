export function getAttackGraphEdgeKind(
  relationType: string | null | undefined,
): AttackGraphEdgeKind {
  const normalized = String(relationType ?? "").trim();
  if (normalized in RELATION_TYPE_TO_EDGE_KIND) {
    return RELATION_TYPE_TO_EDGE_KIND[normalized as AttackGraphRelationType];
  }
  return "unknown";
}

